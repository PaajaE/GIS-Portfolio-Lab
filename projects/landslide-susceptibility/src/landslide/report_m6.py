"""validation/M6_UNCERTAINTY_TRANSFER.md from the M6 JSON files (every number comes from them)."""

from __future__ import annotations

import json

from . import config as C


def _j(name):
    return json.loads((C.VALIDATION / name).read_text())


def f(x, nd=3):
    return "–" if x is None else f"{x:.{nd}f}"


def pct(x):
    return f"{100 * x:.1f} %"


def iv(d, key="ci95"):
    return f"{f(d[key][0])}–{f(d[key][1])}"


def write() -> str:
    S, U, T, W, D = (_j(n) for n in ("m6_sensitivity.json", "m6_uncertainty.json", "m6_trigger.json",
                                      "m6_watauga.json", "m6_watauga_diagnostics.json"))
    L = ["# M6 uncertainty, transfer and sensitivity (5 m logistic regression)", "",
         "Generated by `make m6` from `validation/m6_*.json`. Design fixed before computation (METHOD §Validation, "
         "2026-10-10). Scores are relative ranks, not probabilities of future landslides.", ""]

    L += ["## 1. Sensitivity (one at a time; leave-one-HUC-12-out unless the variant changes it)", "",
          "| Variant | AUC rainfall-stratified | Δ vs primary | AUC within watershed | Δ vs primary | Model − slope (within) | Positive cells |",
          "|---|---|---|---|---|---|---|"]
    labels = {"primary": "Primary", "negative_ratio_1to5": "Negatives 1:5", "negative_ratio_1to20": "Negatives 1:20",
              "positives_ge_50m2": "Positives from polygons ≥ 50 m² only",
              "registration_tolerance_3x3": "Registration tolerance (3×3 maximum)", "domain_ge_300mm": "Domain ≥ 300 mm",
              "terrain_only": "No rainfall covariate", "leave_one_county_out": "**Leave-one-county-out**"}
    rows = [(labels[k], S[k]) for k in labels] + [(f"Training cells removed within {k} of the held-out watershed",
                                                   v) for k, v in S["distance_decay"].items()]
    for lab, v in rows:
        L.append(f"| {lab} | {f(v['auc_rain_stratified'])} | {v.get('delta_vs_primary_rain_stratified', 0):+.3f} | "
                 f"{f(v['auc_within_huc'])} | {v.get('delta_vs_primary_within_huc', 0):+.3f} | "
                 f"{v['model_minus_slope_within_huc']:+.3f} | {v['positives']:,} |")
    bc = S["leave_one_county_out"]["by_county"]
    L += ["", f"- Leave-one-county-out, within-watershed AUC by held-out county: Yancey {f(bc['1'])}, Buncombe {f(bc['2'])}.",
          f"- Polygons < 50 m² removed: {S['positives_ge_50m2']['positives_dropped']:,} positive cells.", "",
          "**Summary layer (5 m score aggregated to slope units) at three unit thresholds:**", "",
          "| A (km²) | Units | Positive units | AUC rainfall-stratified (model / slope p90) | AUC within watershed (model / slope p90) |",
          "|---|---|---|---|---|"]
    for a, v in S["summary_layer_unit_threshold"].items():
        L.append(f"| {a} | {v['units']:,} | {v['positive_units']:,} | {f(v['auc_rain_stratified'])} / "
                 f"{f(v['slope_p90_auc_rain_stratified'])} | {f(v['auc_within_huc'])} / {f(v['slope_p90_auc_within_huc'])} |")

    e, a = U["ensemble"], U["area_of_applicability"]
    L += ["", "## 2. Prediction uncertainty (30 HUC-12 bootstrap refits)", "",
          f"- Of the final model's top 5 / 10 / 20 % cells, {pct(e['final_top5_stays_in_top5_in_90pct_of_refits'])} / "
          f"{pct(e['final_top10_stays_in_top10_in_90pct_of_refits'])} / {pct(e['final_top20_stays_in_top20_in_90pct_of_refits'])} "
          "stay in that class in at least 90 % of refits.",
          f"- {pct(e['final_top10_p90_class_beyond_20'])} of the top-10 % cells fall below the top 20 % in their worst "
          "decile of refits.",
          "- Layers: `data/interim/scores_aoi/ens_rank_p10.tif`, `ens_rank_p90.tif` (class 1–100 per cell).", "",
          "## 3. Area of applicability (Meyer & Pebesma 2021)", "",
          f"- Threshold DI {f(a['threshold_di'])} (training cross-HUC DI quartiles "
          f"{', '.join(f(x) for x in a['training_di_quartiles'])}).",
          f"- {pct(a['share_outside_aoa'])} of the hillslope lattice (50 m) lies outside the area of applicability.",
          "- This covers predictor space only. The transfer tests below show that being inside it does not guarantee "
          "transfer.", ""]

    L += ["## 4. Trigger intensity check (one pre-registered check)", "",
          "| Trigger | T1: units, AUC of trigger alone (pooled) | T2: 5 m model, AUC within watershed |", "|---|---|---|"]
    t1, t2 = T["T1_units_trigger_alone_pooled_auc"], T["T2_cells_within_watershed_auc"]
    for k, lab in (("rain_mm", "72 h total (current)"), ("rain1h_max", "max 1 h"), ("rain6h_max", "max 6 h")):
        L.append(f"| {lab} | {f(t1[k]['auc'])} ({iv(t1[k])}) | {f(t2[k]['auc_within_huc']['value'], 4)} "
                 f"({iv(t2[k]['auc_within_huc'])}) |")
    for k in ("rain1h_max", "rain6h_max"):
        d1, d2, v = t1[f"delta_{k}_minus_72h"], t2[f"delta_{k}_minus_72h"], T["verdict"][k]
        L.append(f"\n- {k}: T1 Δ {d1['value']:+.3f} ({d1['ci95'][0]:+.3f} to {d1['ci95'][1]:+.3f}) → "
                 f"{'pass' if v['T1'] else 'fail'}; T2 Δ {d2['value']:+.4f} ({d2['ci95'][0]:+.4f} to "
                 f"{d2['ci95'][1]:+.4f}) → {'pass' if v['T2'] else 'fail'}; meaningful benefit: "
                 f"**{'yes' if v['meaningful_benefit'] else 'no'}**.")
    L += ["", "Reading: the 6 h maximum explains *where* failures happened better than the 72 h total, but it does "
              "not change the terrain ranking.", ""]

    L += ["## 5. Watauga County (indicative; never in the headline)", "",
          f"Test: {W['helene_test_outlines']} Helene outlines (natural or unassessed, confidence High/Moderate, > 30 m "
          f"from roads; {W['helene_test_cells']:,} proxy cells) vs {W['negatives_test']:,} domain hillslope cells. "
          f"The 1940 outlines ({W['outlines_1940']:,}) are mostly location confidence \"Low\" "
          f"({W['outlines_1940_location_confidence']}).", "",
          "| Score | AUC (95 % interval, bootstrap over outlines) | AUC rainfall-stratified |", "|---|---|---|"]
    for k, lab in (("transfer_aoi_model", "(i) AOI 5 m model, transferred"), ("slope_alone", "Slope alone"),
                   ("temporal_1940_model", "(ii) Model trained on 1940 outlines (15 m smoothed)"),
                   ("recurrence_baseline", "Distance to nearest 1940 outline")):
        L.append(f"| {lab} | {f(W[k]['auc'])} ({iv(W[k])}) | {f(W[k]['auc_rain_stratified'])} |")
    L += ["", "**Post-hoc diagnosis (explanation only, no model changed):**",
          f"- AOI natural initiations lie only in geology groups {sorted(D['geology_share']['aoi_positives'])}; "
          f"{pct(D['geology_share']['watauga_test_positives'].get('2', 0))} of the Watauga test cells are in group 2.",
          f"- Transferred model without its geology terms: AUC {f(D['transfer_auc_without_geology_terms'])} "
          f"(with them {f(D['transfer_auc'])}).",
          "- AOI hillslopes by geology group (share of area, median 72 h rainfall, positive cells): " + "; ".join(
              f"{g}: {pct(v['share'])}, {v['rain_mm_median']:.0f} mm, {v['positive_cells']:,}"
              for g, v in D["aoi_hillslope_by_geology"].items()) + ".",
          "- The rock types without positives are the least rained, so the geology terms largely encode the rainfall "
          "gradient. That is a confound in the product, which the within-AOI validation cannot detect.", ""]
    text = "\n".join(L)
    (C.VALIDATION / "M6_UNCERTAINTY_TRANSFER.md").write_text(text)
    return text


if __name__ == "__main__":
    write()
