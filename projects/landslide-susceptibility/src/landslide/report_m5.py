"""validation/M5_ADVANCED.md from validation/m5_advanced.json (every number comes from the JSON)."""

from __future__ import annotations

import json

import pandas as pd

from . import config as C
from .report_m4 import delta, f, m, pct

CAND = {"a_unit_lr": "(a) Unit logistic regression", "b_unit_gbm": "(b) Unit gradient boosting",
        "c_cell_lr_agg": "(c) 5 m logistic regression → units", "d_cell_gbm_agg": "(d) 5 m gradient boosting → units",
        "slope_p90": "Slope p90 alone (rule reference)"}


def imp_table(a: dict, b: dict, la: str, lb: str) -> list[str]:
    rows = [f"| Predictor group | {la}: Δ AUC stratified | {la}: Δ within | {lb}: Δ AUC stratified | {lb}: Δ within |",
            "|---|---|---|---|---|"]
    for k in sorted(a, key=lambda k: -b[k]["drop_auc_rain_stratified"]):
        rows.append(f"| {k} | {a[k]['drop_auc_rain_stratified']:+.3f} | {a[k]['drop_auc_within_huc']:+.3f} | "
                    f"{b[k]['drop_auc_rain_stratified']:+.3f} | {b[k]['drop_auc_within_huc']:+.3f} |")
    return rows


def write() -> str:
    r = json.loads((C.VALIDATION / "m5_advanced.json").read_text())
    U, P, K = r["units"], r["pixels"], r["criteria"]
    L = ["# M5 advanced model and candidate comparison", "",
         "Generated by `make advanced` from `validation/m5_advanced.json`. Scores are **relative susceptibility "
         "ranks**, not probabilities of future landslides; labels are *mapped* Helene initiation sites.", "",
         "Design as M4 (leave-one-HUC-12-out, 500 m buffer, score at the reference rainfall "
         f"{r['rain_reference_mm']:.0f} mm). Gradient boosting is tuned inside each training fold only (inner CV grouped "
         f"by HUC-12: {r['inner_folds']['units']} folds for units, {r['inner_folds']['pixels']} for cells; metric "
         "rainfall-stratified AUC). Criteria and the product rule were fixed before the first M5 fit "
         "(METHOD §Validation).", "",
         "## Criteria", "",
         f"- **C1** gradient boosting better than logistic regression (lower 95 % bound of Δ stratified AUC > 0): "
         f"units **{'yes' if K['C1_units'] else 'no'}** "
         f"({delta(U['C1_delta_gbm_minus_lr']['auc_rain_stratified'])}), 5 m cells "
         f"**{'yes' if K['C1_pixels'] else 'no'}** ({delta(P['C1_delta_gbm_minus_lr']['auc_rain_stratified'])}).",
         f"- **C2** better than slope alone: passing candidates: "
         f"{', '.join(CAND[c] for c in K['C2_passing']) or '**none**'}.",
         f"- **Product (highest within-watershed AUC among C2 passes):** "
         f"{CAND[K['product']] if K['product'] else '**none: stop for an owner decision**'}. Selecting among four "
         "candidates on the same out-of-fold results is mildly optimistic.", "",
         "## Slope units (out-of-fold; point and 95 % HUC-12 block-bootstrap interval)", "",
         "| Candidate | AUC rainfall-stratified | AUC within watershed | AUC pooled | Capture top 5 % | top 10 % | top 20 % |",
         "|---|---|---|---|---|---|---|"]
    for c, lab in CAND.items():
        s = U["scores"][c]
        L.append(f"| {lab} | {m(s, 'auc_rain_stratified')} | {m(s, 'auc_within_huc')} | {m(s, 'auc_pooled')} | "
                 f"{m(s, 'capture_top5', True)} | {m(s, 'capture_top10', True)} | {m(s, 'capture_top20', True)} |")
    L += ["", "**Δ vs slope p90 alone** (same bootstrap resamples):", "",
          "| Candidate | Δ AUC rainfall-stratified | Δ AUC within watershed |", "|---|---|---|"]
    for c, d in U["C2_delta_vs_slope"].items():
        L.append(f"| {CAND[c]} | {delta(d['auc_rain_stratified'])} | {delta(d['auc_within_huc'])} |")
    L += ["", "**Within-watershed AUC per replicate HUC-12** (≥ 50 positive units):", ""]
    ph = {c: pd.DataFrame(v).set_index("huc12") for c, v in U["per_huc"].items()}
    rep = ph["slope_p90"][ph["slope_p90"]["positive_units"] >= 50].index
    L += ["| HUC-12 | Positive units | " + " | ".join(CAND[c].split(" ")[0] for c in CAND) + " |",
          "|---|---|" + "---|" * len(CAND)]
    for h in rep:
        L.append(f"| {h} | {ph['slope_p90'].loc[h, 'positive_units']} | " +
                 " | ".join(f(ph[c].loc[h, "auc"]) for c in CAND) + " |")
    L += ["", f"Rank correlation (Spearman) between candidates: see `spearman_between_candidates` in the JSON; "
              f"(b) vs (d) = {U['spearman_between_candidates']['b_unit_gbm']['d_cell_gbm_agg']:.3f}, "
              f"(d) vs slope = {U['spearman_between_candidates']['d_cell_gbm_agg']['slope_p90']:.3f}.", ""]
    L += ["## 5 m hillslope cells (out-of-fold)", "",
          "| Score | AUC rainfall-stratified | AUC within watershed | AUC pooled |", "|---|---|---|---|"]
    for k, lab in (("lr", "Logistic regression"), ("gbm", "Gradient boosting"), ("slope", "Slope alone")):
        s = P["scores"][k]
        L.append(f"| {lab} | {m(s, 'auc_rain_stratified')} | {m(s, 'auc_within_huc')} | {m(s, 'auc_pooled')} |")
    L += ["", f"- GBM − slope: stratified {delta(P['delta_gbm_minus_slope']['auc_rain_stratified'])}, within "
              f"watershed {delta(P['delta_gbm_minus_slope']['auc_within_huc'])}.", ""]
    L += ["## Grouped permutation importance (drop in out-of-fold AUC when a group is shuffled)", "",
          "Units:", ""] + imp_table(U["importance_unit_lr"], U["importance_unit_gbm"], "LR", "GBM")
    L += ["", "5 m cells:", ""] + imp_table(P["importance_lr"], P["importance_gbm"], "LR", "GBM")
    L += ["", "Rainfall and unit area are adjustment covariates held at reference values, so they have no importance "
              "in the score by construction.", "",
          "## Artefact audit (units)", "",
          "Out-of-fold residuals after a 1-D recalibration of each score (with rainfall-bin intercepts) against "
          "variables that should not explain them. O/E = observed / expected positive units per quintile "
          "(low → high).", "",
          "| Candidate | Variable | Spearman (residual) | O/E by quintile |", "|---|---|---|---|"]
    for c, d in r["artefact_audit"].items():
        for k, v in d.items():
            L.append(f"| {CAND[c].split(' ')[0]} | {k} | {v['spearman_residual']:+.3f} | "
                     + ", ".join(f"{x:.2f}" for x in v["observed_over_expected_by_quintile"]) + " |")
    cd = U["calibration_diagnostic_unit_gbm"]
    L += ["", f"**Calibration (diagnostic only):** unit GBM Brier {cd['brier']:.4f} vs climatology "
              f"{cd['brier_climatology']:.4f}. Not a probability of a future landslide.", "",
          f"**Tuning:** unit GBM hyper-parameters chosen per fold: {U['chosen_params']}; cells: {P['chosen_params']}.", ""]
    if "error_classes" in r:
        L += ["**Error classes of the product (units):** " +
              ", ".join(f"{k}: {v:,}" for k, v in r["error_classes"].items()) +
              ". A top-ranked unit without a mapped initiation is not a model error: Helene did not test every "
              "susceptible slope, and not every failure was mapped.", ""]
    text = "\n".join(L)
    (C.VALIDATION / "M5_ADVANCED.md").write_text(text)
    return text


if __name__ == "__main__":
    write()
