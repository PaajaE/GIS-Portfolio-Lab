"""validation/M4_BASELINE.md from validation/m4_baseline.json (every number comes from the JSON)."""

from __future__ import annotations

import json

import pandas as pd

from . import config as C


def f(x, nd=3):
    return "–" if x is None or x != x else f"{x:.{nd}f}"


def pct(x):
    return "–" if x is None or x != x else f"{100 * x:.1f} %"


def m(d: dict, key: str, p=False) -> str:
    v = d[key]
    fmt = pct if p else f
    s = fmt(v["value"])
    if "ci95" in v:
        s += f" ({fmt(v['ci95'][0])}–{fmt(v['ci95'][1])})"
    return s


SCORE_LABELS = {
    "lr_at_reference_rain": "Logistic regression, terrain at reference rainfall (**product score**)",
    "lr_actual_rain": "Logistic regression at actual rainfall (contrast: includes trigger)",
    "terrain_only_model": "Logistic regression without rainfall (contrast)",
    "slope_p90_only": "Slope p90 alone (rule reference)",
    "slope_only": "Slope alone (rule reference)",
    "rain_only": "Rainfall alone (trigger footprint)",
}


def score_table(scores: dict, capture=True) -> list[str]:
    head = "| Score | AUC rainfall-stratified | AUC within watershed | AUC pooled | Avg. precision |"
    sep = "|---|---|---|---|---|"
    if capture:
        head += " Capture top 5 % | top 10 % | top 20 % |"
    # average precision is only meaningful against its prevalence baseline (stated below the table)
        sep += "---|---|---|"
    rows = [head, sep]
    for k, s in scores.items():
        r = f"| {SCORE_LABELS.get(k, k)} | {m(s, 'auc_rain_stratified')} | {m(s, 'auc_within_huc')} | " \
            f"{m(s, 'auc_pooled')} | {m(s, 'average_precision')} |"
        if capture:
            r += f" {m(s, 'capture_top5', True)} | {m(s, 'capture_top10', True)} | {m(s, 'capture_top20', True)} |"
        rows.append(r)
    return rows


def delta(d: dict) -> str:
    return f"{d['value']:+.3f} ({d['ci95'][0]:+.3f} to {d['ci95'][1]:+.3f})"


def write(res: dict | None = None) -> str:
    if res is None:
        res = json.loads((C.VALIDATION / "m4_baseline.json").read_text())
    U, P, G, S = res["units"], res["pixels"], res["gates"], res["settings"]
    up, uv = U["primary"], U["slope_only_variant"]
    L = ["# M4 baseline and spatial validation", "",
         "Generated by `make baseline` from `validation/m4_baseline.json`. "
         "Scores are **relative susceptibility ranks**, not probabilities of future landslides. Labels are "
         "*mapped* Helene initiation sites; an unmapped slope is not a proven stable slope.", "",
         "## Design", "",
         f"- Slope units A = {S['unit_A_km2']} km², {U['n_units']:,} units ≥ 50 % in the triggered domain "
         f"(MRMS 72 h ≥ {C.TRIGGER_MM} mm); 5 m hillslope cells as the second unit.",
         f"- Leave-one-HUC-12-out; training rows within {S['buffer_m']} m of the held-out watershed dropped.",
         f"- Rainfall is an adjustment covariate; the score is the prediction at the triggered-domain median "
         f"rainfall ({res['rain_reference_mm']:.0f} mm) and median unit area "
         f"({U['reference_values']['unit_domain_km2']:.3f} km²).",
         f"- Primary metric: AUC within {S['rain_bin_mm']} mm rainfall bins, weighted by positives. "
         "Within-watershed AUC is the strictest view (no between-watershed contrast at all). "
         "Pooled AUC is a contrast.",
         f"- Intervals: 95 % HUC-12 block bootstrap ({S['n_boot']} resamples). Effective n ≈ the number of "
         "watersheds with positives, so intervals are wide.",
         "- No external reference product was scored: the USGS national map (ScienceBase) was not obtained "
         "(optional, scripted download blocked) and the NCGS debris-flow model was published after Helene. "
         "The rule references below are comparisons, not validation.", "",
         "## Decision gates (fixed before the first fit)", "",
         f"- **G1** rainfall-stratified AUC {G['G1']['rule']}: {f(G['G1']['auc'])} "
         f"({f(G['G1']['ci95'][0])}–{f(G['G1']['ci95'][1])}) → **{'pass' if G['G1']['pass'] else 'FAIL'}**",
         f"- **G2** {G['G2']['rule']}: {G['G2']['replicates_above']} of {G['G2']['replicates']} → "
         f"**{'pass' if G['G2']['pass'] else 'FAIL'}**",
         f"- Proceed to M5: **{'yes' if G['proceed_to_M5'] else 'no'}**", "",
         "## Slope units, primary rule (out-of-fold)", "",
         f"Positive units {up['positive_units']:,}, sources {up['sources']:,}. Values: point (95 % CI).", ""]
    L += score_table(up["scores"])
    L += ["", f"Average-precision baseline (prevalence): {f(up['scores']['lr_at_reference_rain']['average_precision']['prevalence_baseline'])}."]
    d1, d2 = up["delta_lr_minus_slope"], up["delta_lr_minus_terrain_only"]
    L += ["", f"- LR − slope p90, rainfall-stratified AUC: {delta(d1['auc_rain_stratified'])}; "
              f"within watershed: {delta(d1['auc_within_huc'])}",
          f"- LR (rain-adjusted) − terrain-only LR, rainfall-stratified AUC: {delta(d2['auc_rain_stratified'])}; "
          f"within watershed: {delta(d2['auc_within_huc'])}", ""]
    r = up["replicates"]
    L += [f"**Replicate watersheds** (≥ {S['replicate_min_positive_units']} positive units, n = {r['n']}): "
          f"within-watershed AUC median {f(r['auc_median'])}, range {f(r['auc_min'])}–{f(r['auc_max'])}; "
          f"capture in the top 10 % of the watershed's area median {pct(r['capture_top10_median'])}.", "",
          "| HUC-12 | Units | Positive units | Sources | AUC | Capture top 10 % |", "|---|---|---|---|---|---|"]
    names = pd.read_csv(C.VALIDATION / "folds_huc12.csv", dtype={"huc12": str}).set_index("huc12")["name"]
    for h in sorted(up["per_huc"], key=lambda x: -x["positive_units"]):
        if h["positive_units"] == 0:
            continue
        L.append(f"| {h['huc12']} {names.get(h['huc12'], '')} | {h['units']:,} | {h['positive_units']} | "
                 f"{h['sources']} | {f(h['auc'])} | {pct(h['capture_top10'])} |")
    zero = [h for h in up["per_huc"] if h["positive_units"] == 0]
    L += ["", f"{len(zero)} further HUC-12s have no positive unit ({sum(h['units'] for h in zero):,} units); "
              "they are held out like the others but cannot be scored on their own.", ""]

    dc = up["design_contrasts"]
    L += ["## Leakage and design contrasts (slope units, point values)", "",
          "| Design | AUC rainfall-stratified | AUC within watershed | AUC pooled | Capture top 10 % |",
          "|---|---|---|---|---|",
          f"| Leave-one-HUC-12-out, {S['buffer_m']} m buffer (primary) | "
          f"{f(up['scores']['lr_at_reference_rain']['auc_rain_stratified']['value'])} | "
          f"{f(up['scores']['lr_at_reference_rain']['auc_within_huc']['value'])} | "
          f"{f(up['scores']['lr_at_reference_rain']['auc_pooled']['value'])} | "
          f"{pct(up['scores']['lr_at_reference_rain']['capture_top10']['value'])} |"]
    for k, lab in (("loho_huc12_no_buffer", "Leave-one-HUC-12-out, no buffer"),
                   ("leave_one_huc10_out", f"Leave-one-HUC-10-out ({dc['huc10_groups']} groups)"),
                   ("random_5fold", "Random 5-fold (leaky contrast)")):
        s = dc[k]
        L.append(f"| {lab} | {f(s['auc_rain_stratified']['value'])} | {f(s['auc_within_huc']['value'])} | "
                 f"{f(s['auc_pooled']['value'])} | {pct(s['capture_top10']['value'])} |")
    hd = up["heldout_positive_to_nearest_training_positive_m"]
    L += ["", f"- Held-out positive units → nearest positive unit in another watershed: median {hd['median']:.0f} m, "
              f"p10 {hd['p10']:.0f} m, {pct(hd['share_lt_1km'])} within 1 km.",
          "- Correlation of out-of-fold Pearson residuals between units by distance:", "",
          "| Distance (km) | Pairs | r |", "|---|---|---|"]
    for c in up["residual_correlogram"]:
        L.append(f"| {c['km'][0]}–{c['km'][1]} | {c['pairs']:,} | {f(c['r'])} |")
    cd = up["calibration_diagnostic"]
    oe = up["county_observed_over_expected"]
    cn = {1: "Yancey", 2: "Buncombe"}
    L += ["", "## Bias checks", "",
          f"- **Mapping effort by county** (observed / expected positive units, out-of-fold, conditioned on terrain "
          f"and rainfall): " + ", ".join(f"{cn.get(int(k), k)} {v:.2f}" for k, v in oe.items()) + ".",
          f"- **Units whose only Helene sources are non-primary** (road-related etc., labelled 0): "
          f"{up['units_with_only_nonprimary_sources']['n']:,}; rainfall-stratified AUC without them "
          f"{f(up['units_with_only_nonprimary_sources']['auc_rain_stratified_without_them'])}.",
          f"- **Calibration (diagnostic only, not shown in the app):** Brier {cd['brier']:.4f} vs climatology "
          f"{cd['brier_climatology']:.4f} (skill {cd['brier_skill']:.3f}). This is fit to one event's mapped "
          "inventory, so it is not a probability of a future landslide.", ""]
    pp = P["primary"]
    nb = pp["negative_sample_bias"]
    L += ["## 5 m hillslope cells (out-of-fold)", "",
          f"Positive cells {pp['positive_cells']:,}; negatives = M3 pool on hillslopes "
          f"({P['hillslope_pool_negatives']:,}, weight {P['negative_weight']:.1f}); 1:{S['neg_ratio']} per training fold. "
          "Capture uses the unrestricted domain sample for area.", ""]
    L += score_table({"lr_at_reference_rain": pp["scores"]["lr_at_reference_rain"]})
    L += score_table({"slope_only": pp["scores"]["slope_only"]}, capture=False)[2:]
    L += ["", f"Average-precision baseline (prevalence-weighted): "
              f"{pp['scores']['lr_at_reference_rain']['average_precision']['prevalence_baseline']:.5f}."]
    d = pp["delta_lr_minus_slope"]
    L += ["", f"- LR − slope, rainfall-stratified AUC: {delta(d['auc_rain_stratified'])}; within watershed: "
              f"{delta(d['auc_within_huc'])}",
          f"- Random 5-fold contrast: rainfall-stratified AUC "
          f"{f(pp['design_contrasts']['random_5fold']['auc_rain_stratified']['value'])}.",
          f"- **Negative-sample bias:** rainfall-stratified AUC vs the exclusion-filtered pool "
          f"{f(nb['auc_rain_stratified_vs_pool'])}, vs unrestricted domain cells {f(nb['auc_rain_stratified_vs_unrestricted_domain'])} "
          f"(within watershed {f(nb['auc_within_huc_vs_unrestricted_domain'])}). Excluded cells are "
          f"{pct(nb['excluded_share_of_domain_sample'])} of the domain; their scores vs eligible cells: AUC "
          f"{f(nb['excluded_vs_eligible_auc'])} (> 0.5 = excluded cells rank higher).", ""]
    vc = U["variant_comparison"]
    L += ["## Positive rule: primary vs slope-only variant", "",
          f"Variant (runoff-modified natural slopes included): {uv['positive_units']:,} positive units, "
          f"{uv['sources']:,} sources. Values: point (95 % CI).", ""]
    L += score_table({"lr_at_reference_rain": uv["scores"]["lr_at_reference_rain"]})
    L += ["", f"- Spearman correlation of out-of-fold scores, primary vs variant model: {vc['spearman_oof_scores']:.3f}.",
          f"- Both models scored on primary labels, primary − variant: rainfall-stratified AUC "
          f"{delta(vc['delta_primary_model_minus_variant_model_on_primary_labels']['auc_rain_stratified'])}; "
          f"within watershed {delta(vc['delta_primary_model_minus_variant_model_on_primary_labels']['auc_within_huc'])}.",
          f"- Pixel variant: rainfall-stratified AUC "
          f"{m(P['slope_only_variant']['scores']['lr_at_reference_rain'], 'auc_rain_stratified')} vs primary "
          f"{m(pp['scores']['lr_at_reference_rain'], 'auc_rain_stratified')}.", ""]
    co = up["coefficients_standardized"]
    L += ["## Coefficients (standardized; final all-data model, range over folds)", "",
          "| Predictor | Final | Fold min | Fold max | Folds kept |", "|---|---|---|---|---|"]
    for k, v in sorted(co.items(), key=lambda kv: -abs(kv[1]["final"])):
        L.append(f"| {k} | {v['final']:+.3f} | {v['fold_min']:+.3f} | {v['fold_max']:+.3f} | {v['folds_kept']} |")
    L += ["", f"Not selected (VIF > 10 given higher-priority predictors) in the final unit model: "
              f"{', '.join(up['vif_pruned_in_final']) or 'none'}; in the final 5 m model: "
              f"{', '.join(pp['vif_pruned_in_final']) or 'none'}.", ""]
    text = "\n".join(L)
    (C.VALIDATION / "M4_BASELINE.md").write_text(text)
    return text


if __name__ == "__main__":
    write()
